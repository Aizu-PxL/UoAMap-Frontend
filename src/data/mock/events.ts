import type { Event as CampusEvent, TimeSlot } from "../types";

// 会津大学オープンキャンパス2026 夏ステージ（2026-08-08）の
// 2026-07-31確認済みデータを現行Eventへ変換したもの。
// 元データのprograms[].tags（詳細タグ101種類）はユーザー判断により取り込まず、
// 正式IDの先頭文字に対応する9カテゴリだけをEvent.tagsへ保持する。
const DAY = "2026-08-08";

function slot(start: string, end?: string): TimeSlot {
  return end
    ? { start: `${DAY}T${start}:00+09:00`, end: `${DAY}T${end}:00+09:00` }
    : { start: `${DAY}T${start}:00+09:00` };
}

function event(
  id: string | undefined,
  title: string,
  description: string,
  placeId: string,
  tags: string[],
  timeSlots: TimeSlot[],
  key = id,
): CampusEvent {
  if (!key) {
    throw new TypeError("Eventの内部keyが必要です");
  }
  return {
    key,
    ...(id === undefined ? {} : { id }),
    title,
    description,
    placeId,
    tags,
    timeSlots,
  };
}

type Occurrence = {
  id: string;
  start: string;
  end?: string;
};

function repeatedEvents(
  title: string,
  description: string,
  placeId: string,
  tag: string,
  occurrences: readonly Occurrence[],
  numbered = false,
): CampusEvent[] {
  return occurrences.map((occurrence, index) =>
    event(
      occurrence.id,
      numbered ? `${title}（${index + 1}回目）` : title,
      description,
      placeId,
      [tag],
      [slot(occurrence.start, occurrence.end)],
    ),
  );
}

